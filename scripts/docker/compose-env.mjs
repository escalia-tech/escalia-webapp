#!/usr/bin/env node
import { buildImageReference, resolveGitRevision, resolveGitSource } from "./image-metadata.mjs";
/**
 * Writes `.env.compose` with ESCALIA_IMAGE derived from package.json (never hand-edited versions in compose.yaml).
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const OUT = join(process.cwd(), ".env.compose");

try {
  const ref = buildImageReference({
    registry: process.env.DOCKER_REGISTRY,
    namespace: process.env.DOCKER_NAMESPACE,
  });
  const revision = resolveGitRevision();
  const source = resolveGitSource();

  const lines = [
    `# Generated by npm run docker:compose:env — do not commit`,
    `ESCALIA_IMAGE=${ref.image}`,
    `ESCALIA_HOST_PORT=${process.env.ESCALIA_HOST_PORT ?? "3000"}`,
    ...(revision ? [`ESCALIA_APP_REVISION=${revision}`] : []),
    ...(source ? [`ESCALIA_APP_SOURCE=${source}`] : []),
    "",
  ];

  writeFileSync(OUT, lines.join("\n"), "utf8");
  process.stdout.write(`Wrote ${OUT}\n`);
  process.stdout.write(`ESCALIA_IMAGE=${ref.image}\n`);
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exit(1);
}
